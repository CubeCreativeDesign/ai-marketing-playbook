#!/usr/bin/env python3
from __future__ import annotations
"""
qc-structure-check.py

Scans a blog draft for structural violations:
  - Bold-as-heading: lines matching **Text.** followed by a paragraph
  - Horizontal rules in body: standalone ---, ***, or ___ outside YAML frontmatter
  - H4+ headings: #### or deeper (posts use H1-H3 only)
  - Bold-without-period-as-heading: **Text** alone on a line above a paragraph

Outputs JSON to stdout.

Usage:
  qc-structure-check.py <draft.md>

Exit codes:
  0 = analysis complete
  1 = file not found or parse error
"""
import argparse
import json
import re
import sys
from pathlib import Path


# Bold-as-heading: **Text** or **Text.** alone on a line, followed by non-empty content.
BOLD_HEADING_RE = re.compile(r'^\s*\*\*([^*\n]{2,120})\*\*\s*$')
# Horizontal rule patterns.
HR_RE = re.compile(r'^\s*(?:-{3,}|\*{3,}|_{3,})\s*$')
# H4+ headings.
H4_PLUS_RE = re.compile(r'^(#{4,})\s+(.+?)\s*$')


def detect_frontmatter_range(lines: list[str]) -> tuple[int, int]:
    """Return (start_line, end_line) of YAML frontmatter, or (-1, -1) if none."""
    if not lines or lines[0].strip() != '---':
        return -1, -1
    for i in range(1, len(lines)):
        if lines[i].strip() == '---':
            return 0, i
    return -1, -1


def detect_pipeline_metadata_range(lines: list[str]) -> tuple[int, int]:
    """Return (0, end_line) of the pipeline Publishing Package metadata block.

    The pipeline prefixes drafts with '# Publishing Package' metadata. The
    article body begins at the first H1 that is neither '# Publishing Package'
    nor a title-option line (title options end with a bare character count like
    "(49)"). Everything before that H1 is pipeline metadata and is excluded.
    """
    if not lines or not lines[0].strip().startswith('# Publishing Package'):
        return -1, -1
    for i, line in enumerate(lines[1:], start=1):
        stripped = line.strip()
        if not re.match(r'^#\s+', stripped):
            continue
        if stripped.startswith('# Publishing Package'):
            continue
        # Title options end with a bare char count: "(49)", "(55)", etc.
        if re.search(r'\(\d+\)\s*$', stripped):
            continue
        # This is the article H1 — exclude everything before it.
        return 0, i - 1
    return -1, -1


def detect_code_fence_ranges(lines: list[str]) -> list[tuple[int, int]]:
    """Return list of (start_line, end_line) tuples for code fences."""
    ranges = []
    fence_start = None
    for i, line in enumerate(lines):
        if line.strip().startswith('```'):
            if fence_start is None:
                fence_start = i
            else:
                ranges.append((fence_start, i))
                fence_start = None
    return ranges


def line_in_ranges(line_idx: int, ranges: list[tuple[int, int]]) -> bool:
    """Return True if line_idx falls within any of the given (start, end) ranges."""
    for start, end in ranges:
        if start <= line_idx <= end:
            return True
    return False


def strip_qc_report(text: str) -> str:
    """Strip any existing auto-generated QC report block from the draft.
    Prevents the structure check from flagging the report's own subheadings.
    Also removes the trailing '---' separator that preceded the QC block."""
    text = re.sub(
        r'\n*##?#?\s+Stage\s+3\s+QC\s+Report\s+\(auto-generated by qc.sh\).*',
        '',
        text,
        flags=re.DOTALL,
    )
    # Remove any trailing --- left behind as the pre-QC separator.
    return re.sub(r'\n+\s*-{3,}\s*$', '', text)


def check_structure(draft_path: Path) -> dict:
    text = strip_qc_report(draft_path.read_text(encoding='utf-8'))
    lines = text.splitlines()

    fm_start, fm_end = detect_frontmatter_range(lines)
    frontmatter_range = [(fm_start, fm_end)] if fm_start >= 0 else []
    pm_start, pm_end = detect_pipeline_metadata_range(lines)
    pipeline_metadata_range = [(pm_start, pm_end)] if pm_start >= 0 else []
    code_fence_ranges = detect_code_fence_ranges(lines)
    excluded_ranges = frontmatter_range + pipeline_metadata_range + code_fence_ranges

    bold_heading_violations = []
    horizontal_rule_violations = []
    h4_plus_violations = []

    for i, line in enumerate(lines):
        if line_in_ranges(i, excluded_ranges):
            continue

        # Bold-as-heading detection.
        bold_match = BOLD_HEADING_RE.match(line)
        if bold_match:
            # Look ahead: is the next non-empty line a paragraph (not another heading)?
            next_content_line = None
            for j in range(i + 1, min(i + 5, len(lines))):
                if line_in_ranges(j, excluded_ranges):
                    continue
                stripped = lines[j].strip()
                if stripped:
                    next_content_line = lines[j]
                    break
            # If followed by paragraph content (not a heading, not a list, not blank),
            # this is bold-as-heading misuse.
            if next_content_line and not re.match(r'^\s*(?:#|\*|-|\d+\.|\||>)', next_content_line):
                bold_heading_violations.append({
                    'line_number': i + 1,
                    'line_text': line.strip(),
                    'extracted_text': bold_match.group(1).strip(),
                    'suggested_fix': f'### {bold_match.group(1).strip().rstrip(".")}',
                })

        # Horizontal rule detection.
        if HR_RE.match(line):
            horizontal_rule_violations.append({
                'line_number': i + 1,
                'line_text': line.strip(),
            })

        # H4+ heading detection.
        h4_match = H4_PLUS_RE.match(line)
        if h4_match:
            level = len(h4_match.group(1))
            h4_plus_violations.append({
                'line_number': i + 1,
                'line_text': line.strip(),
                'heading_level': level,
                'heading_text': h4_match.group(2).strip(),
                'suggested_fix': f'### {h4_match.group(2).strip()}',
            })

    summary = {
        'bold_as_heading_violations': len(bold_heading_violations),
        'horizontal_rule_violations': len(horizontal_rule_violations),
        'h4_plus_violations': len(h4_plus_violations),
        'total_violations': (
            len(bold_heading_violations)
            + len(horizontal_rule_violations)
            + len(h4_plus_violations)
        ),
    }

    return {
        'draft_path': str(draft_path),
        'summary': summary,
        'bold_as_heading_violations': bold_heading_violations,
        'horizontal_rule_violations': horizontal_rule_violations,
        'h4_plus_violations': h4_plus_violations,
    }


def main():
    parser = argparse.ArgumentParser(description='Check draft for structural violations.')
    parser.add_argument('draft', type=Path, help='Path to the draft markdown file.')
    args = parser.parse_args()

    if not args.draft.exists():
        print(json.dumps({'error': f'Draft not found: {args.draft}'}), file=sys.stderr)
        sys.exit(1)

    try:
        result = check_structure(args.draft)
        print(json.dumps(result, indent=2))
    except Exception as e:
        print(json.dumps({'error': f'{type(e).__name__}: {e}'}), file=sys.stderr)
        sys.exit(1)


if __name__ == '__main__':
    main()
