#!/usr/bin/env python3
from __future__ import annotations
"""
qc-readability.py

Computes readability metrics for a blog draft, measured against
the MAIN BODY ONLY (introduction through conclusion). Strips:
  - TL;DR section: everything between {{TLDR}} and {{endTLDR}}
  - FAQ section: everything between {{FAQ}} and {{endFAQ}}
  - Links section: everything from `# Links` heading onward
  - Stage 3 scan report block
  - YAML frontmatter (between --- markers at top of file)

Reports:
  - Word count (main body)
  - Sentence count
  - Average sentence length (words)
  - Flesch-Kincaid grade level (ceiling: 9, warn only)
  - Flesch Reading Ease (floor: 60, warn only; easier copy is never a miss)
  - Em-dash count
  - Em-dashes per 300 words (limit: 1, warn only)
  - Passive voice sentence ratio (rough heuristic)

Outputs JSON to stdout.

Usage:
  qc-readability.py <draft.md>

Exit codes:
  0 = analysis complete
  1 = file not found or parse error
"""
import argparse
import json
import re
import sys
from pathlib import Path

try:
    import textstat
except ImportError:
    print(json.dumps({
        'error': 'textstat is not installed. Run: pip install textstat'
    }), file=sys.stderr)
    sys.exit(1)


# Past-participle pattern for rough passive voice detection.
# Catches: was/were/been/being/is/are/am + (optional adverb) + verb ending in -ed/-en/-t
PASSIVE_RE = re.compile(
    r'\b(?:was|were|been|being|is|are|am|be)\b\s+'
    r'(?:\w+ly\s+)?'  # optional adverb
    r'\w+(?:ed|en)\b',
    re.IGNORECASE
)


def strip_qc_report(text: str) -> str:
    """Strip any existing auto-generated QC report block from the draft.
    This makes re-runs idempotent — the scripts never analyze their own output."""
    return re.sub(
        r'\n*##?#?\s+Stage\s+3\s+QC\s+Report\s+\(auto-generated by qc.sh\).*',
        '',
        text,
        flags=re.DOTALL,
    )


def strip_excluded_sections(text: str) -> str:
    """Strip QC report, TL;DR, FAQ, and Links sections from the text."""
    # Strip any previously-appended QC report FIRST.
    text = strip_qc_report(text)
    # Cut the publishing package first, while the {{TLDR}} marker still exists to anchor
    # the body start. (Before 2026-09-29 the TL;DR block was removed first, so this
    # always fell through to 'Recommended Titles' and the title rationale leaked in.)
    _tldr0 = re.search(r'\{\{TLDR\}\}', text)
    if _tldr0:
        text = text[_tldr0.start():]
    # Strip TL;DR wrapper content (everything between {{TLDR}} and {{endTLDR}}).
    text = re.sub(r'\{\{TLDR\}\}.*?\{\{endTLDR\}\}', '', text, flags=re.DOTALL)
    # Strip FAQ wrapper content.
    text = re.sub(r'\{\{FAQ\}\}.*?\{\{endFAQ\}\}', '', text, flags=re.DOTALL)
    # Strip from "# Links" heading to end of file.
    text = re.sub(r'^#\s+Links\s*$.*', '', text, flags=re.MULTILINE | re.DOTALL)
    # Strip the publishing package that Stage 4 and Stage 5 prepend above the body.
    #
    # That block is title candidates, meta descriptions, keyword lists and slug rationale:
    # terse, noun-dense, sentence-fragment writing that is never published as prose. Feeding
    # it to Flesch-Kincaid inflates the grade by roughly a point. The body starts at {{TLDR}} when the marker is present; otherwise it starts
    # at the "## Recommended Titles" section that always closes the package.
    _tldr = re.search(r'\{\{TLDR\}\}', text)
    if _tldr:
        text = text[_tldr.start():]
    else:
        _pkg = re.search(r'^#+\s+Recommended Titles\s*$', text, flags=re.MULTILINE)
        if _pkg:
            text = text[_pkg.end():]
    # Strip leftover wrapper markers.
    text = re.sub(r'\{\{(?:TLDR|endTLDR|FAQ|endFAQ)\}\}', '', text)
    return text


def strip_frontmatter(text: str) -> str:
    """Remove YAML frontmatter if present at the start of the file."""
    if text.lstrip().startswith('---'):
        lines = text.split('\n')
        if lines[0].strip() == '---':
            for i in range(1, len(lines)):
                if lines[i].strip() == '---':
                    return '\n'.join(lines[i + 1:])
    return text





def strip_markdown_for_analysis(text: str) -> str:
    """Strip markdown syntax that would distort readability metrics."""
    # Remove code fences and their content
    text = re.sub(r'```.*?```', '', text, flags=re.DOTALL)
    # Remove inline code
    text = re.sub(r'`[^`]+`', '', text)
    # Remove markdown links but keep the link text: [text](url) -> text
    text = re.sub(r'\[([^\]]+)\]\([^)]+\)', r'\1', text)
    # Remove images entirely
    text = re.sub(r'!\[[^\]]*\]\([^)]+\)', '', text)
    # Remove heading markers but keep heading text
    text = re.sub(r'^#{1,6}\s+', '', text, flags=re.MULTILINE)
    # Remove bold/italic markers
    text = re.sub(r'(\*\*|__)([^*_]+)\1', r'\2', text)
    text = re.sub(r'(\*|_)([^*_]+)\1', r'\2', text)
    # Remove blockquote markers
    text = re.sub(r'^>\s*', '', text, flags=re.MULTILINE)
    # Remove markdown tables entirely, not just their pipes.
    #
    # Turning "| Source | URL | Verdict |" into "Source URL Verdict" fed terse noun phrases
    # and bare URLs to the Flesch-Kincaid formula as if they were sentences, which inflated
    # the grade by roughly 1.5 to 2.5 points on every post carrying verification tables. The
    # October 2026 batch reported FK 10.1-11.7 across 13 drafts; measured on prose alone the
    # same drafts run 8.6-9.8. Tables are reference data, not prose, and the readability
    # target is a prose target. Drop the rows.
    text = re.sub(r'^\s*\|.*$', '', text, flags=re.MULTILINE)
    # Remove HTML tags
    text = re.sub(r'<[^>]+>', '', text)
    # Remove list markers
    text = re.sub(r'^\s*[-*+]\s+', '', text, flags=re.MULTILINE)
    text = re.sub(r'^\s*\d+\.\s+', '', text, flags=re.MULTILINE)
    # Collapse whitespace
    text = re.sub(r'\n{3,}', '\n\n', text)
    return text.strip()


def count_em_dashes(text: str) -> int:
    """Count em dashes (—) in the text. Excludes em dashes used as horizontal
    rules (lines that are JUST em dashes)."""
    count = 0
    for line in text.splitlines():
        stripped = line.strip()
        if stripped and all(c in '\u2014- ' for c in stripped):
            continue  # likely a horizontal rule, skip
        count += line.count('\u2014')
    return count


def estimate_passive_voice_ratio(text: str) -> tuple[int, int]:
    """Return (passive sentence count, total sentence count) as a rough estimate."""
    sentences = re.split(r'(?<=[.!?])\s+', text)
    sentences = [s for s in sentences if s.strip() and len(s.strip()) > 5]
    passive = sum(1 for s in sentences if PASSIVE_RE.search(s))
    return passive, len(sentences)


def opening_sentence(text: str) -> str | None:
    """First sentence of the intro (12 words or fewer).

    The intro starts under '## Introduction'. Without one, it starts under the H1,
    and with no H1 at all it starts at the top.
    Template markers, headings, quotes, tables, and images are skipped.
    """
    lines = text.splitlines()
    start = next((i for i, l in enumerate(lines) if l.startswith('## Introduction')), None)
    if start is None:
        start = next((i for i, l in enumerate(lines) if l.startswith('# ')), None)
    if start is None:
        start = -1  # no heading at all (client drafts): the body starts at line 1
    for line in lines[start + 1:]:
        s = line.strip()
        if not s or s.startswith(('{{', '#', '>', '|', '![', '<')):
            continue
        s = re.sub(r'\[([^\]]*)\]\([^)]*\)', r'\1', s).replace('**', '')
        m = re.match(r'(.+?[.?!]["\u201d\u2019)]*)(?:\s|$)', s)  # a closing quote can follow the period
        return m.group(1) if m else s
    return None


def project_targets(draft_path: Path) -> dict:
    """Readability ceilings. A project can override them in reference/readability-targets.json
    (for example {"fk_max": 10, "fre_min": 55} for a more technical audience).
    Default: grade 9, Reading Ease 60."""
    targets = {'fk_max': 9.0, 'fre_min': 60.0}
    for parent in [draft_path.resolve().parent] + list(draft_path.resolve().parents):
        f = parent / 'reference' / 'readability-targets.json'
        if f.exists():
            targets.update(json.loads(f.read_text()))
            break
    return targets


def analyze(draft_path: Path) -> dict:
    raw_text = draft_path.read_text(encoding='utf-8')
    tg = project_targets(draft_path)
    text = strip_frontmatter(raw_text)
    main_body = strip_excluded_sections(text)
    clean_text = strip_markdown_for_analysis(main_body)

    if not clean_text.strip():
        return {
            'draft_path': str(draft_path),
            'error': 'No main body content found after stripping TL;DR/FAQ/Links sections.',
        }

    word_count = textstat.lexicon_count(clean_text, removepunct=True)
    sentence_count = textstat.sentence_count(clean_text)
    avg_sentence_length = word_count / sentence_count if sentence_count > 0 else 0
    fk_grade = textstat.flesch_kincaid_grade(clean_text)
    fre = textstat.flesch_reading_ease(clean_text)

    em_dash_count = count_em_dashes(main_body)
    em_dashes_per_200 = (em_dash_count / word_count) * 200 if word_count > 0 else 0
    em_dashes_per_300 = (em_dash_count / word_count) * 300 if word_count > 0 else 0

    opening = opening_sentence(text)
    # Weak openers and reader-first pronouns.
    weak_openers = len(re.findall(r"(?:^|[.!?]\s+)(?:There is|There are|There's|It is)\b", clean_text, re.M))
    intensifiers = len(re.findall(r"\b(?:very|really)\b", clean_text, re.I))
    we_count = len(re.findall(r"\b(?:we|our|ours|us)\b", clean_text, re.I))
    you_count = len(re.findall(r"\b(?:you|your|yours)\b", clean_text, re.I))
    opening_words = len(opening.split()) if opening else None

    passive_count, total_sentences = estimate_passive_voice_ratio(clean_text)
    passive_ratio = (passive_count / total_sentences) if total_sentences > 0 else 0

    # Pass/fail flags against the readability targets.
    # Note: "too easy to read" is not a problem — operators on phones are fine
    # with simpler prose. Only flag when content drifts ABOVE the target.
    flags = {
        # Ceilings only. A miss is a warning, never a fail.
        'flesch_kincaid_in_target': fk_grade <= tg['fk_max'],
        'flesch_kincaid_acceptable': True,
        'flesch_reading_ease_in_target': fre >= tg['fre_min'],
        'flesch_reading_ease_acceptable': True,
        'em_dash_ratio_under_limit': em_dashes_per_300 <= 1.0,   # 1 per 300 words, warn only (2026-09-29)
        'avg_sentence_length_under_22': avg_sentence_length < 22.0,
        'passive_ratio_under_15pct': passive_ratio < 0.15,
        'opening_sentence_under_13': opening_words is None or opening_words <= 12,
        'weak_openers_under_4': weak_openers <= 3,
        'no_intensifiers': intensifiers == 0,
        'reader_first': we_count <= you_count,
    }

    return {
        'draft_path': str(draft_path),
        'word_count_main_body': word_count,
        'sentence_count': sentence_count,
        'avg_sentence_length': round(avg_sentence_length, 1),
        'flesch_kincaid_grade': round(fk_grade, 1),
        'flesch_reading_ease': round(fre, 1),
        'em_dash_count': em_dash_count,
        'em_dashes_per_200_words': round(em_dashes_per_200, 2),
        'em_dashes_per_300_words': round(em_dashes_per_300, 2),
        'passive_voice_count': passive_count,
        'passive_voice_ratio': round(passive_ratio, 3),
        'opening_sentence': opening,
        'opening_sentence_words': opening_words,
        'weak_openers': weak_openers,
        'intensifiers': intensifiers,
        'we_our_count': we_count,
        'you_your_count': you_count,
        'flags': flags,
        'targets': {
            'flesch_kincaid_grade': f"<={tg['fk_max']:g}",
            'flesch_reading_ease': f">={tg['fre_min']:g}",
            'em_dashes_per_300_words': '<=1',
            'avg_sentence_length': '<22',
            'passive_voice_ratio': '<15%',
            'opening_sentence_words': '<=12',
        },
    }


def main():
    parser = argparse.ArgumentParser(description='Compute readability metrics for a draft.')
    parser.add_argument('draft', type=Path, help='Path to the draft markdown file.')
    args = parser.parse_args()

    if not args.draft.exists():
        print(json.dumps({'error': f'Draft not found: {args.draft}'}), file=sys.stderr)
        sys.exit(1)

    try:
        result = analyze(args.draft)
        print(json.dumps(result, indent=2))
    except Exception as e:
        print(json.dumps({'error': f'{type(e).__name__}: {e}'}), file=sys.stderr)
        sys.exit(1)


if __name__ == '__main__':
    main()
