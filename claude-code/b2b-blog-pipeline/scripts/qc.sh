#!/usr/bin/env bash
#
# qc.sh — Run all QC checks on a blog draft and produce a
# markdown report block ready to paste into the draft.
#
# Usage:
#   qc.sh <draft.md>                  # print markdown report to stdout
#   qc.sh <draft.md> --json           # print raw JSON from all three scripts
#   qc.sh <draft.md> --append         # append/replace report inside the draft (idempotent)
#
# Exit codes:
#   0 = all scripts ran successfully (regardless of violations found)
#   1 = one or more scripts errored
#   2 = invalid arguments
#

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PYTHON="${PYTHON:-python3}"

usage() {
    cat <<EOF
Usage: qc.sh <draft.md> [--json|--append]

Runs qc-prohibited-scan, qc-readability, and qc-structure-check
on the draft and produces a consolidated markdown QC report.

Options:
  --json     Print raw JSON output from each script (machine-readable).
  --append   Append the markdown report block to the draft file.
             Idempotent — replaces any previous auto-generated block.
  -h, --help Show this help.
EOF
}

# Parse args.
DRAFT=""
MODE="markdown"  # markdown | json | append

if [[ $# -lt 1 ]]; then
    usage >&2
    exit 2
fi

while [[ $# -gt 0 ]]; do
    case "$1" in
        -h|--help) usage; exit 0 ;;
        --json) MODE="json"; shift ;;
        --append) MODE="append"; shift ;;
        *)
            if [[ -z "$DRAFT" ]]; then
                DRAFT="$1"
            else
                echo "Unexpected argument: $1" >&2
                usage >&2
                exit 2
            fi
            shift
            ;;
    esac
done

if [[ -z "$DRAFT" ]]; then
    echo "Error: no draft file provided." >&2
    usage >&2
    exit 2
fi

if [[ ! -f "$DRAFT" ]]; then
    echo "Error: draft file not found: $DRAFT" >&2
    exit 1
fi

# Run all three scripts, capturing output to temp files.
TMPDIR_QC="$(mktemp -d)"
trap 'rm -rf "$TMPDIR_QC"' EXIT

if ! "$PYTHON" "$SCRIPT_DIR/qc-prohibited-scan.py" "$DRAFT" > "$TMPDIR_QC/prohibited.json" 2> "$TMPDIR_QC/prohibited.err"; then
    echo "qc-prohibited-scan.py failed:" >&2
    cat "$TMPDIR_QC/prohibited.err" >&2
    exit 1
fi

if ! "$PYTHON" "$SCRIPT_DIR/qc-readability.py" "$DRAFT" > "$TMPDIR_QC/readability.json" 2> "$TMPDIR_QC/readability.err"; then
    echo "qc-readability.py failed:" >&2
    cat "$TMPDIR_QC/readability.err" >&2
    exit 1
fi

if ! "$PYTHON" "$SCRIPT_DIR/qc-structure-check.py" "$DRAFT" > "$TMPDIR_QC/structure.json" 2> "$TMPDIR_QC/structure.err"; then
    echo "qc-structure-check.py failed:" >&2
    cat "$TMPDIR_QC/structure.err" >&2
    exit 1
fi

# JSON mode: bundle all three.
if [[ "$MODE" == "json" ]]; then
    "$PYTHON" - "$TMPDIR_QC" <<'PYEOF'
import json
import sys
from pathlib import Path
tmp = Path(sys.argv[1])
out = {
    "prohibited_phrase_scan": json.loads((tmp / "prohibited.json").read_text()),
    "readability": json.loads((tmp / "readability.json").read_text()),
    "structure_check": json.loads((tmp / "structure.json").read_text()),
}
print(json.dumps(out, indent=2))
PYEOF
    exit 0
fi

# Build markdown report by reading the three JSON files via Python.
"$PYTHON" - "$TMPDIR_QC" > "$TMPDIR_QC/report.md" <<'PYEOF'
import json
import sys
from pathlib import Path

tmp = Path(sys.argv[1])
prohibited = json.loads((tmp / "prohibited.json").read_text())
readability = json.loads((tmp / "readability.json").read_text())
structure = json.loads((tmp / "structure.json").read_text())

lines = []
lines.append("## Stage 3 QC Report (auto-generated by qc.sh)")
lines.append("")
lines.append(
    "This report is generated by the qc.sh script suite. It is internal-only "
    "and will be stripped by the CMS publishing step. Do not edit by hand. "
    "Re-run qc.sh after fixing issues to regenerate."
)
lines.append("")

# ------- Prohibited-Phrase Scan -------
ps = prohibited.get("summary", {})
lines.append("### Prohibited-Phrase Scan")
lines.append("")
lines.append(f"- Terms scanned from prohibited-phrases.md: **{ps.get('total_terms_scanned', 0)}**")
lines.append(f"- Total hits: **{ps.get('total_hits', 0)}**")
lines.append(f"- Own voice (must be rewritten): **{ps.get('own_voice_hits', 0)}**")
lines.append(f"- In blockquote (preserve verbatim): **{ps.get('blockquote_hits', 0)}**")
lines.append(
    f"- In attributed quote (preserve verbatim, flagged for human review): "
    f"**{ps.get('attributed_quote_hits', 0)}**"
)
lines.append(
    f"- Proper noun (real program or acronym, do not reword): "
    f"**{ps.get('proper_noun_hits', 0)}**"
)
lines.append(
    f"- Inside a URL (rewording would break the link): **{ps.get('url_hits', 0)}**"
)
lines.append(
    f"- Cited post title (rewording would misquote it): **{ps.get('cited_title_hits', 0)}**"
)
lines.append(f"- AI-tell words (warning, use only if necessary): **{ps.get('avoid_hits', 0)}**")
lines.append(f"- Contrast frame over its limit (warning): **{ps.get('limit_exceeded_hits', 0)}**")
lines.append(f"- Emoji (warning): **{ps.get('emoji_hits', 0)}**")
lines.append(f"- Results claim with no number, link, or source nearby (warning): **{ps.get('unproven_claim_hits', 0)}**")
lines.append(f"- Heading verb with no number or result (warning): **{ps.get('heading_verb_hits', 0)}**")
lines.append(f"- Vague quantity in a sentence with a stat (warning): **{ps.get('vague_quantity_hits', 0)}**")
lines.append(f"- Attribution with a named source (OK): **{ps.get('sourced_hits', 0)}**")
lines.append("")

hits = prohibited.get("hits", [])
if hits:
    lines.append("| Term | Matched | Line | Section | Classification |")
    lines.append("|------|---------|------|---------|----------------|")
    classification_label = {
        "own_voice": "**FIX** Own voice",
        "in_blockquote": "Keep (blockquote)",
        "in_attributed_quote": "Review (attributed quote)",
        "proper_noun": "Keep (proper noun)",
        "in_url": "Keep (inside a URL)",
        "link_text": "Keep (link text, not a placeholder)",
        "example_query": "Keep (bracket inside a quoted example query)",
        "example_dialogue": "Keep (chatbot phrase inside quoted example dialogue)",
        "cited_title": "Keep (cited post title)",
        "avoid": "WARN AI-tell word (make it specific: a number, name, or detail)",
        "limit_exceeded": "WARN contrast frame over limit",
        "limit_ok": "Keep (within limit)",
        "emoji": "WARN emoji",
        "sourced": "Keep (source named)",
        "claim_unproven": "WARN claim needs proof (number, name, or source)",
        "claim_proven": "Keep (proof nearby)",
        "heading_verb": "WARN empty heading verb (add a number or result)",
        "heading_verb_ok": "Keep (heading carries a number)",
        "vague_quantity": "WARN vague quantity next to a stat (use the exact figure)",
    }
    for h in hits:
        label = classification_label.get(h["classification"], h["classification"])
        section = h.get("section", "")
        if len(section) > 50:
            section = section[:50] + "..."
        # Escape pipes inside table cells.
        section = section.replace("|", "\\|")
        matched = h["matched_text"].replace("|", "\\|")
        term = h["term"].replace("|", "\\|")
        lines.append(f"| {term} | {matched} | {h['line_number']} | {section} | {label} |")
    lines.append("")
else:
    lines.append("No prohibited-phrase hits found.")
    lines.append("")

# ------- Readability -------
lines.append("### Readability Metrics (Main Body Only)")
lines.append("")
if "error" in readability:
    lines.append(f"_Could not compute readability: {readability['error']}_")
    lines.append("")
else:
    flags = readability.get("flags", {})

    def status(in_target_flag, acceptable_flag=None):
        if flags.get(in_target_flag):
            return "PASS"
        if acceptable_flag and flags.get(acceptable_flag):
            return "WARN"
        return "FAIL"

    lines.append(f"- Word count (main body): **{readability['word_count_main_body']}**")
    lines.append(f"- Sentence count: {readability['sentence_count']}")
    lines.append(
        f"- Average sentence length: **{readability['avg_sentence_length']}** words "
        f"(target <22) — {status('avg_sentence_length_under_22')}"
    )
    if "weak_openers" in readability:
        def pw(flag):
            return 'PASS' if flags.get(flag, True) else 'WARN'
        lines.append(f"- 'There is/are', 'It is' openers: **{readability['weak_openers']}** (3 or fewer, warn only) — {pw('weak_openers_under_4')}")
        lines.append(f"- 'very' / 'really': **{readability['intensifiers']}** (0, warn only) — {pw('no_intensifiers')}")
        lines.append(f"- we/our vs. you/your: **{readability['we_our_count']} / {readability['you_your_count']}** (reader first, warn only) — {pw('reader_first')}")
    if readability.get("opening_sentence_words") is not None:
        lines.append(
            f"- Opening sentence: **{readability['opening_sentence_words']}** words "
            f"(12 or fewer, lead with the problem, warn only) — {'PASS' if flags.get('opening_sentence_under_13', True) else 'WARN'}"
        )
    lines.append(
        f"- Flesch-Kincaid grade: **{readability['flesch_kincaid_grade']}** "
        f"(ceiling {readability.get('targets', {}).get('flesch_kincaid_grade', '<=9')}, warn only) — {status('flesch_kincaid_in_target', 'flesch_kincaid_acceptable')}"
    )
    lines.append(
        f"- Flesch Reading Ease: **{readability['flesch_reading_ease']}** "
        f"(floor {readability.get('targets', {}).get('flesch_reading_ease', '>=60')}, warn only) — {status('flesch_reading_ease_in_target', 'flesch_reading_ease_acceptable')}"
    )
    lines.append(
        f"- Em-dash count: **{readability['em_dash_count']}** "
        f"({readability.get('em_dashes_per_300_words', 'n/a')} per 300 words, limit 1, warn only) — "
        f"{'PASS' if flags.get('em_dash_ratio_under_limit') else 'WARN'}"
    )
    lines.append(
        f"- Passive voice ratio: **{int(readability['passive_voice_ratio']*100)}%** "
        f"({readability['passive_voice_count']} sentences, target <15%) — "
        f"{status('passive_ratio_under_15pct')}"
    )
    lines.append("")

# ------- Structure -------
lines.append("### Structure Check")
lines.append("")
ss = structure.get("summary", {})
lines.append(f"- Bold-as-heading violations: **{ss.get('bold_as_heading_violations', 0)}**")
lines.append(f"- Horizontal rule violations: **{ss.get('horizontal_rule_violations', 0)}**")
lines.append(f"- H4+ heading violations: **{ss.get('h4_plus_violations', 0)}**")
lines.append("")

has_structure_violations = (
    structure.get("bold_as_heading_violations")
    or structure.get("horizontal_rule_violations")
    or structure.get("h4_plus_violations")
)

if has_structure_violations:
    lines.append("| Type | Line | Current | Suggested Fix |")
    lines.append("|------|------|---------|---------------|")
    for v in structure.get("bold_as_heading_violations", []):
        current = v["line_text"].replace("|", "\\|")
        fix = v.get("suggested_fix", "").replace("|", "\\|")
        lines.append(f"| Bold-as-heading | {v['line_number']} | `{current}` | `{fix}` |")
    for v in structure.get("horizontal_rule_violations", []):
        current = v["line_text"].replace("|", "\\|")
        lines.append(f"| Horizontal rule | {v['line_number']} | `{current}` | Replace with a heading |")
    for v in structure.get("h4_plus_violations", []):
        current = v["line_text"].replace("|", "\\|")
        fix = v.get("suggested_fix", "").replace("|", "\\|")
        lines.append(f"| H{v['heading_level']} (too deep) | {v['line_number']} | `{current}` | `{fix}` |")
    lines.append("")
else:
    lines.append("No structural violations found.")
    lines.append("")

# ------- Overall Status -------
lines.append("### Overall QC Status")
lines.append("")
own_voice_hits = ps.get("own_voice_hits", 0)
structure_violations = ss.get("total_violations", 0)
total_required_fixes = own_voice_hits + structure_violations

readability_failures = 0
if "flags" in readability:
    fl = readability["flags"]
    if not fl.get("flesch_kincaid_in_target"):
        readability_failures += 1
    if not fl.get("flesch_reading_ease_in_target"):
        readability_failures += 1
    if not fl.get("em_dash_ratio_under_limit"):
        readability_failures += 1
    if not fl.get("avg_sentence_length_under_22"):
        readability_failures += 1
    if not fl.get("opening_sentence_under_13", True):
        readability_failures += 1
    for _flag in ("weak_openers_under_4", "no_intensifiers", "reader_first"):
        if not fl.get(_flag, True):
            readability_failures += 1

# Phrase warnings (2026-09-29): AI-tell words, contrast frame over limit, emoji.
phrase_warnings = (ps.get("avoid_hits", 0) + ps.get("limit_exceeded_hits", 0) + ps.get("emoji_hits", 0)
                   + ps.get("unproven_claim_hits", 0) + ps.get("heading_verb_hits", 0)
                   + ps.get("vague_quantity_hits", 0))

if total_required_fixes == 0 and readability_failures == 0 and phrase_warnings == 0:
    lines.append(
        "**PASS** — No required fixes detected by automated checks. Manual checks "
        "(standalone readability per H2/H3 block, H2 answer-pattern compliance) still "
        "need to be performed by Claude."
    )
elif total_required_fixes == 0:
    lines.append(
        f"**WARN** — {readability_failures} readability target(s) missed, "
        f"{phrase_warnings} phrase warning(s) (AI-tell words, contrast frame, emoji, unproven claims, heading verbs, vague quantities). "
        f"Review and adjust prose before publishing. Automated structural checks passed."
    )
else:
    lines.append(
        f"**FAIL** — {total_required_fixes} required fix(es) detected "
        f"({own_voice_hits} prohibited-phrase, {structure_violations} structural). "
        f"Address all flagged items, then re-run qc.sh to regenerate this report."
    )
lines.append("")

print("\n".join(lines))
PYEOF

# Output handling.
if [[ "$MODE" == "append" ]]; then
    # Idempotent: strip any existing auto-generated block before appending.
    "$PYTHON" - "$DRAFT" "$TMPDIR_QC/report.md" <<'PYEOF'
import re
import sys
from pathlib import Path

draft_path = Path(sys.argv[1])
report_path = Path(sys.argv[2])

content = draft_path.read_text(encoding="utf-8")
# Remove any existing auto-generated report block.
content = re.sub(
    r'\n*##?#?\s+Stage 3 QC Report \(auto-generated by qc.sh\).*',
    '',
    content,
    flags=re.DOTALL,
)
content = content.rstrip() + "\n\n"
report = report_path.read_text(encoding="utf-8").rstrip() + "\n"
draft_path.write_text(content + report, encoding="utf-8")
PYEOF
    echo "Report appended to: $DRAFT" >&2
else
    cat "$TMPDIR_QC/report.md"
fi
